/** Prix HT d'une case de grille : tient compte de la variante (x 1,15). */
export function prixGrille(g: Grille, h: Cote, l: Cote): number | null {
	const base = g.baseId ? (GRILLE_BY_ID.get(g.baseId) ?? g) : g;
	const ligne = base.lignes.find((x) => x.d.v === h.v);
	if (!ligne) return null;
	const i = base.cols.findIndex((c) => c.v === l.v);
	if (i < 0) return null;
	const v = ligne.p[i];
	if (v == null) return null;
	return Math.round(v * (g.mult ?? 1) * 100) / 100;
}
